import { findStartMonths } from './irregular';

// 現物給与の変化も固定的賃金の変動（日本年金機構「現物給与の価額 Q&A」Q3。11/24）
const p = (m: string, fixed: number, inKind: number | null, extra: Record<string, unknown> = {}) =>
  [m, { paidMonth: m, cash: fixed, fixed, fixedFull: null, inKind, retro: 0, prorated: false, state: 'normal', ...extra }] as const;
const found = (rows: ReturnType<typeof p>[], opts = {}) =>
  findStartMonths(new Map(rows) as any, [], opts).map((s) => [s.month, s.source, s.direction]);

describe('findStartMonths：現物給与の変化', () => {
  it('社宅に月の初めから入居：その月が起算月（上がる）', () => {
    expect(found([p('2026-03', 250000, 0), p('2026-04', 250000, 45280), p('2026-05', 250000, 45280)])).toEqual([
      ['2026-04', 'inKind', 'up'],
    ]);
  });

  it('月の途中で入居（日割り）：次の月が起算月（Q7・事例7）', () => {
    // 4/11 入居：30,186円（日割り）→ 5月から 45,280円
    expect(found([p('2026-03', 250000, 0), p('2026-04', 250000, 30186), p('2026-05', 250000, 45280), p('2026-06', 250000, 45280)])).toEqual([
      ['2026-05', 'inKind', 'up'],
    ]);
  });

  it('月の途中で退去（日割り）：次の月が起算月（下がる）', () => {
    expect(found([p('2026-03', 250000, 45280), p('2026-04', 250000, 20000), p('2026-05', 250000, 0), p('2026-06', 250000, 0)])).toEqual([
      ['2026-05', 'inKind', 'down'],
    ]);
  });

  it('価額の改正（住宅は 2026-10 から㎡）も起算月になる', () => {
    expect(found([p('2026-09', 250000, 45280), p('2026-10', 250000, 53200), p('2026-11', 250000, 53200)])).toEqual([
      ['2026-10', 'inKind', 'up'],
    ]);
  });

  it('住宅手当をやめて社宅にした（通貨は下がり、現物が上がる）：向きは合わせて決める', () => {
    // 住宅手当 30,000 をやめ、社宅 45,280 → 合わせて +15,280
    expect(found([p('2026-03', 280000, 0), p('2026-04', 250000, 45280), p('2026-05', 250000, 45280)])).toEqual([
      ['2026-04', 'fixed', 'up'],
    ]);
    // ちょうど打ち消すと向きは要確認
    expect(found([p('2026-03', 295280, 0), p('2026-04', 250000, 45280)])).toEqual([['2026-04', 'fixed', 'unclear']]);
  });

  it('現物の内訳なし（null）の月とは比べない', () => {
    expect(found([p('2026-03', 250000, null), p('2026-04', 250000, 45280), p('2026-05', 250000, 45280)])).toEqual([]);
  });

  it('時給の人（額で比べない月）でも、現物の変化は見つける', () => {
    const opts = { amountComparable: () => false };
    expect(found([p('2026-03', 120000, 0), p('2026-04', 135000, 25500), p('2026-05', 110000, 25500)], opts)).toEqual([
      ['2026-04', 'inKind', 'up'],
    ]);
  });

  it('現物が変わらなければ今までどおり（通貨の固定的賃金だけで見る）', () => {
    expect(found([p('2026-03', 250000, 25500), p('2026-04', 270000, 25500), p('2026-05', 270000, 25500)])).toEqual([
      ['2026-04', 'fixed', 'up'],
    ]);
  });
});

describe('固定的賃金の向き：現物がある人の「時間外手当が0円になった」', () => {
  it('現物（寮）がある人でも、通貨の非固定的賃金が0円になったら向きは要確認', () => {
    const rows = [
      p('2026-04', 300000, 20000, { cash: 330000 }),
      p('2026-05', 350000, 20000),
      p('2026-06', 350000, 20000),
    ];
    expect(found(rows)).toEqual([['2026-05', 'fixed', 'unclear']]);
  });
});
